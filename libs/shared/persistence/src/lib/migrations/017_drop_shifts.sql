-- El turno deja de existir.
--
-- Existía para el sector que hoy no cubre nadie: sus mesas quedaban asignadas
-- a un ausente y no aparecían en la pantalla de ninguno. Con una mesa a cargo
-- de varios ese caso lo resuelve el reparto —si uno falta, el otro la tiene
-- igual— así que la ceremonia de entrar y salir dejó de pagar lo que costaba.
--
-- Ahora el filtro sale sólo del reparto: con sector se ven las propias, sin
-- sector se ve todo.
DROP TABLE IF EXISTS staff_shifts;
